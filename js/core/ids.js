/**
 * Identificadores internos estables, compatibles con UUID v4.
 * Nunca se usa el nombre visible como clave primaria.
 */

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Genera un UUID v4 usando la Web Crypto API (navegador y Node >= 19). */
export function createId() {
  const c = globalThis.crypto;
  if (c && typeof c.randomUUID === 'function') return c.randomUUID();
  if (c && typeof c.getRandomValues === 'function') {
    const bytes = new Uint8Array(16);
    c.getRandomValues(bytes);
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    const hex = Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
  }
  throw new Error('No hay generador criptográfico disponible para crear IDs.');
}

/** true si el texto tiene formato UUID. */
export function isUuid(value) {
  return typeof value === 'string' && UUID_RE.test(value);
}
